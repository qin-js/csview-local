import { chromium } from 'playwright';
import os from 'node:os';
import path from 'node:path';
import fs from 'node:fs';
const OUT = path.join(os.tmpdir(), 'csview-shots');
fs.mkdirSync(OUT, { recursive: true });
const b = await chromium.launch({ executablePath: process.env.CHROME_BIN || undefined });
const c = await b.newContext({ viewport:{width:1440,height:900} });
const p = await c.newPage();
const go = async (h, ms=1000) => { await p.goto((process.env.BASE_URL || 'http://localhost:5173') + '/'+h, {waitUntil:'networkidle'}); await p.waitForTimeout(ms); };
const snap = (n) => p.screenshot({path:`${OUT}/v-${n}.png`});
await go('#/d/network-tcp'); await snap('reader-top');
await p.evaluate(()=>{document.documentElement.style.scrollBehavior='auto';scrollTo(0,1400)}); await p.waitForTimeout(600); await snap('reader-mid');
await go('#/d/algorithm-tree-01'); await p.evaluate(()=>{document.documentElement.style.scrollBehavior='auto';scrollTo(0,700)}); await p.waitForTimeout(700); await snap('reader-code');
await go('#/rank'); await snap('rank');
await go('#/quiz'); await snap('quiz-setup');
await p.click('[data-no-cats]'); await p.click('[data-qc=redis]'); await p.locator('#cntRange').fill('10'); await p.click('[data-start]'); await p.waitForTimeout(600);
await snap('quiz-q');
await p.click('[data-reveal]'); await p.waitForTimeout(900); await snap('quiz-a');
await go('#/progress'); await snap('progress');
await go('#/c/cpp'); await snap('category');
await go('#/about'); await snap('about');
await p.keyboard.press('Control+k'); await p.waitForTimeout(700); await p.fill('#palInput','索引'); await p.waitForTimeout(600); await snap('search');
await p.keyboard.press('Escape');
await p.click('#themeBtn'); await p.waitForTimeout(500);
await go('#/d/mysql-indexing'); await snap('light-reader');
await go('#/'); await snap('light-home');
await b.close();
